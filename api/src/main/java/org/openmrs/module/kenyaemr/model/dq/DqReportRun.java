package org.openmrs.module.kenyaemr.model.dq;

import org.openmrs.BaseOpenmrsObject;
import org.openmrs.User;

import java.util.Date;

/**
 * One generated version of one report for one period. Every regeneration creates a new version;
 * older versions are kept and marked SUPERSEDED. This is the record the HRIO approves, and the one
 * the KHIS submission ledger in kenyaemrIL refers to.
 */
public class DqReportRun extends BaseOpenmrsObject {

	public static final String APPROVAL_MODE_MANUAL = "MANUAL";

	/** Approved by the deadline task because nobody approved it in time (auto-send on the 5th) */
	public static final String APPROVAL_MODE_AUTO = "AUTO";

	private Integer id;

	/** Report name as used in the KHIS mapping file, e.g. "MOH-743 Report" */
	private String reportName;

	/** Target uuid of the kenyacore report descriptor */
	private String reportUuid;

	private Date periodStart;

	private Date periodEnd;

	private Integer version;

	private DqRunStatus status;

	/** SHA-256 of the stored values, so identical regenerations can be recognised */
	private String valuesHash;

	private Date generatedAt;

	/** Null when generated by the scheduled task */
	private User generatedBy;

	private User approvedBy;

	private Date approvedAt;

	private String approvalMode;

	@Override
	public Integer getId() {
		return id;
	}

	@Override
	public void setId(Integer id) {
		this.id = id;
	}

	public String getReportName() {
		return reportName;
	}

	public void setReportName(String reportName) {
		this.reportName = reportName;
	}

	public String getReportUuid() {
		return reportUuid;
	}

	public void setReportUuid(String reportUuid) {
		this.reportUuid = reportUuid;
	}

	public Date getPeriodStart() {
		return periodStart;
	}

	public void setPeriodStart(Date periodStart) {
		this.periodStart = periodStart;
	}

	public Date getPeriodEnd() {
		return periodEnd;
	}

	public void setPeriodEnd(Date periodEnd) {
		this.periodEnd = periodEnd;
	}

	public Integer getVersion() {
		return version;
	}

	public void setVersion(Integer version) {
		this.version = version;
	}

	public DqRunStatus getStatus() {
		return status;
	}

	public void setStatus(DqRunStatus status) {
		this.status = status;
	}

	public String getValuesHash() {
		return valuesHash;
	}

	public void setValuesHash(String valuesHash) {
		this.valuesHash = valuesHash;
	}

	public Date getGeneratedAt() {
		return generatedAt;
	}

	public void setGeneratedAt(Date generatedAt) {
		this.generatedAt = generatedAt;
	}

	public User getGeneratedBy() {
		return generatedBy;
	}

	public void setGeneratedBy(User generatedBy) {
		this.generatedBy = generatedBy;
	}

	public User getApprovedBy() {
		return approvedBy;
	}

	public void setApprovedBy(User approvedBy) {
		this.approvedBy = approvedBy;
	}

	public Date getApprovedAt() {
		return approvedAt;
	}

	public void setApprovedAt(Date approvedAt) {
		this.approvedAt = approvedAt;
	}

	public String getApprovalMode() {
		return approvalMode;
	}

	public void setApprovalMode(String approvalMode) {
		this.approvalMode = approvalMode;
	}
}
